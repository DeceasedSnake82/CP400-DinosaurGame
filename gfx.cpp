uint16_t* fb;

void init() {
#ifdef DINO_HOST
    fb = LCD_GetVRAMAddress();
#else
    fb = vram;                          // fixed VRAM address from calc.h
#endif
}

void fillSpan(uint16_t* dst, int pixels, uint16_t c) {
    const uint32_t p = pair(c);
    u32a* d = (u32a*)dst;
    for (int i = pixels >> 1; i > 0; --i) *d++ = p;
    if (pixels & 1) dst[pixels - 1] = c;
}

void copyPixels(uint16_t* dst, const uint16_t* src, int pixels) {
    u32a* d = (u32a*)dst;
    const u32a* s = (const u32a*)src;
    int n = pixels >> 1;
    for (; n >= 4; n -= 4) { d[0] = s[0]; d[1] = s[1]; d[2] = s[2]; d[3] = s[3]; d += 4; s += 4; }
    for (; n > 0; --n) *d++ = *s++;
}

void fillRect(int x, int y, int w, int h, uint16_t c) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > W) w = W - x;
    if (y + h > H) h = H - y;
    if (w <= 0 || h <= 0) return;
    for (int j = 0; j < h; ++j) {
        uint16_t* d = fb + (y + j) * W + x;
        for (int i = 0; i < w; ++i) d[i] = c;
    }
}

void frameRect(int x, int y, int w, int h, uint16_t c) {
    fillRect(x, y, w, 1, c);
    fillRect(x, y + h - 1, w, 1, c);
    fillRect(x, y, 1, h, c);
    fillRect(x + w - 1, y, 1, h, c);
}

