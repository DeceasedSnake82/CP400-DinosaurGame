int textWidth(const char* s, int scale) {
    int n = 0;
    while (s[n]) ++n;
    return n ? n * 6 * scale - scale : 0;
}

void text(int x, int y, const char* s, int scale, uint16_t c) {
    for (; *s; ++s, x += 6 * scale) {
        int ch = (unsigned char)*s;
        if (ch >= 'a' && ch <= 'z') ch -= 32;
        if (ch < 0x20 || ch > 0x5F) ch = '?';
        const uint8_t* g = FONT[ch - 0x20];
        for (int row = 0; row < 7; ++row) {
            const uint8_t bits = g[row];
            for (int col = 0; col < 5; ++col)
                if (bits & (0x10 >> col)) fillRect(x + col * scale, y + row * scale, scale, scale, c);
        }
    }
}

char* putStr(char* d, const char* s) {
    while (*s) *d++ = *s++;
    *d = 0;
    return d;
}

char* putInt(char* d, int32_t v) {
    char tmp[12];
    int n = 0;
    uint32_t u = (uint32_t)v;
    if (v < 0) { *d++ = '-'; u = 0u - u; }
    do { tmp[n++] = (char)('0' + u % 10); u /= 10; } while (u);
    while (n) *d++ = tmp[--n];
    *d = 0;
    return d;
}

